import { YARE } from './brand';
import type { CatalogEntry } from './catalog';
import { projectRef } from './components/ConnectionsPanel';

export interface GuideInput {
  apps: CatalogEntry[];
  repoUrl: string | null;
  /** Undefined when none of the apps needs a database. */
  supabaseUrl?: string;
  supabasePublishableKey?: string;
  email?: string;
}

/**
 * The "use my AI assistant" path for the whole collection: a Markdown file the operator hands to
 * their assistant (or pastes into a tool such as Lovable). It contains only public values. The
 * database password and Cloudflare sign-in happen at the operator's keyboard when the assistant
 * asks, never in this file.
 */
export function buildSetupGuide({ apps, repoUrl, supabaseUrl, supabasePublishableKey, email }: GuideInput): string {
  const repo = repoUrl ?? YARE.repo;
  const date = new Date().toISOString().slice(0, 10);
  const lines: string[] = [];
  const add = (...l: string[]) => lines.push(...l);

  const needsDb = apps.some((a) => a.database);
  const title = apps.length === 1 ? `Install ${apps[0]!.name}` : 'Set up my Yare Monster apps';
  add(`# ${title}`, '', `Generated by ${apps.length === 1 ? apps[0]!.name : 'Yare Launcher'} on ${date}${email ? ` for ${email}` : ''}.`, '',
    `You are helping me install ${apps.length === 1 ? 'one Yare Monster app' : `${apps.length} Yare Monster apps`} on my own accounts. Yare Monster (${YARE.url}) is a collection of free, self-hosted apps; every app lives in its own folder and runs on my Supabase project and my Cloudflare account. Nothing is sent to Yare Monster.`, '',
    `## Rules for you, the assistant`, '',
    `- Work one app at a time, in the order below. Finish one before starting the next.`,
    `- Ask me to sign in when a tool needs it (GitHub, Supabase CLI, Cloudflare). Do not try to work around a sign-in.`,
    `- The only secret you will handle is my Supabase database password, which I will type when the Supabase CLI asks. Never write it into a file, a commit or a message.`,
    `- Do not change application code. Configuration files (\`.env\`, \`wrangler.jsonc\`) are the only files you edit.`,
    `- Tell me the address of each deployed app when it is live. I will open it myself.`, '',
    `## My accounts`, '',
    `- Code: ${repoUrl ? `my copy of the repository, ${repoUrl}` : `the official repository, ${YARE.repo} (I have not made my own copy yet; clone the official one)`}`,
    ...(needsDb ? [`- Database: Supabase project ${supabaseUrl ?? '(I will give you the project URL and publishable key)'}`] : []),
    `- Hosting: Cloudflare (I will sign in when Wrangler asks)`, '');
  if (needsDb) {
    add(`## Values every app uses`, '',
      'These two are public; they end up in the browser bundle by design.', '',
      '```', `VITE_SUPABASE_URL=${supabaseUrl ?? 'https://<my-project-ref>.supabase.co'}`, `VITE_SUPABASE_PUBLISHABLE_KEY=${supabasePublishableKey ?? '<my publishable key>'}`, '```', '');
  }
  add(
    `## Steps`, '',
    `### 0. Get the code`, '',
    '```sh', `git clone ${repo} yare`, 'cd yare', '```', '',
    'Node.js 20 or newer is required (`node --version`).', '');

  apps.forEach((app, i) => {
    const folder = `apps/yare-${app.slug}`;
    add(`### ${i + 1}. ${app.name}`, '', `${app.line} Folder: \`${folder}\`. Its README and DEPLOYMENT.md are the authority if anything here disagrees.`, '',
      '```sh', `cd ${folder}`, 'npm install', '```', '');
    if (app.database) {
      add('Create `.env` with the two values above.', '',
        apps.filter((a) => a.database).length > 1
          ? 'Database: already done in step 0b.'
          : 'Push its database migrations to my Supabase project (ask me for the project ref if you cannot read it from the URL; the CLI asks me for the database password):', '',
        ...(apps.filter((a) => a.database).length > 1 ? [] : ['```sh', 'npx supabase login', `npx supabase link --project-ref ${(supabaseUrl && projectRef(supabaseUrl)) ?? '<my-project-ref>'}`, 'npx supabase db push --linked', '```', '']));
    } else {
      add('This app has no database. Skip the Supabase step.', '');
    }
    add('Build and deploy to my Cloudflare account (Wrangler opens a browser for me to sign in the first time):', '',
      '```sh', 'npm run build', 'npx wrangler deploy', '```', '',
      ...(app.database ? [
      'Allow my email to create the account (ask me which email if you do not know it):', '',
      '```sh', `npx supabase db query "select public.yare_allow_email('${email ?? 'me@example.com'}')" --linked`, '```', '',
    ] : []),
    `Tell me the \`workers.dev\` address Wrangler prints. ${app.database ? 'I will open it, create my account with that email and sign in.' : 'I will open it and check it loads.'}`, '',
      `Then \`cd ../..\` and continue.`, '');
  });

  add(`## When everything is deployed`, '',
    `- List every app and its address.`,
    `- Remind me to add a custom domain in Cloudflare for any app I want on my own domain (Worker → Settings → Domains & Routes).`,
    `- Remind me to mark each app as set up in Yare Launcher and paste its address there.`, '',
    `## If something fails`, '',
    `- "Almost there" screen in an app: a VITE_ value is missing or still a placeholder. Fix \`.env\`, rebuild, redeploy.`,
    `- "This email is not on the list": run the yare_allow_email step above for my email, then I try again.`,
    `- "That email already has an account": I sign in instead of creating one.`,
    `- Migration errors: run \`npx supabase db push --linked\` again; the files are safe to repeat.`, '',
    `---`, '', `Yare Monster, created by Orlando Pedro. ${YARE.url}`, '');
  return lines.join('\n');
}


export function downloadText(filename: string, text: string) {
  const blob = new Blob([text], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
